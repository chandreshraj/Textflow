test('keeps the displayed result and panel height stable during a slow preview', async ({ page }) => {
 await page.goto('/')
 const output = page.getByLabel('Output text')
 await expect(output).toHaveText('Real Python!')
 const before = await page.locator('.output-card').boundingBox()
 let release: (() => void) | undefined
 await page.route('**/api/transform', async route => {
  await new Promise<void>(resolve => { release = resolve })
  await route.continue()
 })
 await page.getByLabel('Input text').fill('Fake Java')
 await expect(page.locator('.preview-status')).toHaveText('Updating')
 await expect(output).toHaveText('Real Python!')
 await expect(page.getByText('Previous result', { exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Copy', exact: true })).toBeDisabled()
 const during = await page.locator('.output-card').boundingBox()
 expect(Math.abs(during!.height - before!.height)).toBeLessThanOrEqual(1)
 await expect.poll(() => !!release).toBe(true)
 release!()
 await expect(output).toHaveText('Real Java!')
 await expect(page.locator('.preview-status')).toHaveText('Updated')
 await expect(page.getByRole('button', { name: 'Copy', exact: true })).toBeEnabled()
})
