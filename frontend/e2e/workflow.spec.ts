import { test, expect } from '@playwright/test'
test('discover, configure, reorder, execute and validate a pipeline', async ({ page }) => {
 await page.goto('/')
 await expect(page.getByRole('button', { name: 'Add Replace', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Run pipeline', exact: true }).click()
 await expect(page.getByLabel('Output text')).toHaveText('Real Python!')
 await page.getByLabel('Input text').fill('Fake Java')
 await expect(page.getByLabel('Output text')).toHaveCount(0)
 await page.getByRole('button', { name: 'Run pipeline', exact: true }).click()
 await expect(page.getByLabel('Output text')).toHaveText('Real Java!')
 await page.getByRole('button', { name: 'Add Prepend', exact: true }).click()
 await page.getByRole('button', { name: 'Move step 3 up', exact: true }).click()
 await page.getByRole('button', { name: 'Run pipeline', exact: true }).click()
 await expect(page.getByLabel('Output text')).toHaveText('Hello, Real Java!')
 await page.getByLabel('Find', { exact: true }).fill('')
 await page.getByRole('button', { name: 'Run pipeline', exact: true }).click()
 await expect(page.getByRole('alert')).toContainText('Find text cannot be empty')
 await page.getByRole('button', { name: 'Load example' }).click()
 await page.getByRole('button', { name: 'Run pipeline', exact: true }).click()
 await page.evaluate(() => window.scrollTo(0, 0))
 await page.screenshot({ path: '../docs/desktop.png', fullPage: true })
 await page.setViewportSize({ width: 390, height: 844 })
 await expect(page.getByRole('button', { name: 'Run pipeline', exact: true })).toBeVisible()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
 await page.screenshot({ path: '../docs/mobile.png', fullPage: true })
})
