test('discovers Normalize Whitespace and previews both boolean options', async ({ page }) => {
 await page.goto('/')
 await page.getByRole('button', { name: 'Clear all', exact: true }).click()
 await page.getByLabel('Input text').fill('  Hello \t world \n \t Goodbye   moon  ')
 await page.getByRole('button', { name: 'Add Normalize Whitespace', exact: true }).click()
 const output = page.getByLabel('Output text')
 await expect(output).toHaveJSProperty('textContent', 'Hello world\nGoodbye moon')
 await page.getByLabel('Preserve line breaks', { exact: true }).uncheck()
 await expect(output).toHaveJSProperty('textContent', 'Hello world Goodbye moon')
 await page.getByLabel('Trim edges', { exact: true }).uncheck()
 await expect(output).toHaveJSProperty('textContent', ' Hello world Goodbye moon ')
 await page.getByLabel('Trim edges', { exact: true }).check()
 await expect(output).toHaveJSProperty('textContent', 'Hello world Goodbye moon')
})

test('automatically encodes and decodes URL components with validation recovery', async ({ page }) => {
 await page.goto('/')
 await page.getByRole('button', { name: 'Clear all', exact: true }).click()
 await page.getByLabel('Input text').fill('café + tea')
 await page.getByRole('button', { name: 'Add URL encode/decode', exact: true }).click()
 await expect(page.getByLabel('Output text')).toHaveText('caf%C3%A9%20%2B%20tea')
 await page.getByLabel('URL mode', { exact: true }).selectOption('Decode')
 await page.getByLabel('Input text').fill('caf%C3%A9%20%2B%20tea')
 await expect(page.getByLabel('Output text')).toHaveText('café + tea')
 await page.getByLabel('Input text').fill('%GG')
 await expect(page.getByRole('alert')).toContainText('Each percent escape')
 await page.getByLabel('Input text').fill('hello%20world')
 await expect(page.getByLabel('Output text')).toHaveText('hello world')
})

