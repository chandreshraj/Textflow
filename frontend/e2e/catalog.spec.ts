import { test, expect } from '@playwright/test'

for (const viewport of [{ width: 1280, height: 720 }, { width: 390, height: 640 }]) {
 test(`catalog scrolls only the list at ${viewport.width}px`, async ({ page }) => {
  await page.setViewportSize(viewport)
  await page.goto('/')
  const heading = page.getByRole('heading', { name: 'Transformations', exact: true })
  const search = page.getByRole('textbox', { name: 'Search transformations' })
  const list = page.getByRole('region', { name: 'Available transformations' })
  await expect(list.getByRole('button', { name: 'Add URL encode/decode', exact: true })).toBeAttached()
  const headingBefore = await heading.boundingBox()
  const searchBefore = await search.boundingBox()
  const pageScrollBefore = await page.evaluate(() => window.scrollY)
  await list.evaluate(el => { el.scrollTop = el.scrollHeight })
  expect(await list.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect((await heading.boundingBox())!.y).toBeCloseTo(headingBefore!.y, 0)
  expect((await search.boundingBox())!.y).toBeCloseTo(searchBefore!.y, 0)
  expect(await page.locator('.catalog').evaluate(el => el.scrollTop)).toBe(0)
  expect(await page.evaluate(() => window.scrollY)).toBe(pageScrollBefore)
  await search.fill('URL')
  await expect(list.getByRole('button', { name: /^Add / })).toHaveCount(1)
  await list.getByRole('button', { name: 'Add URL encode/decode', exact: true }).click()
  await expect(page.getByLabel('Output text')).toHaveText('Real%20Python%21')
 })
}


for (const viewport of [{ width: 1280, height: 720 }, { width: 390, height: 844 }]) {
 test(`transformation descriptions use independent accessible info controls at ${viewport.width}px`, async ({ page }) => {
  await page.setViewportSize(viewport)
  await page.goto('/')
  const info = page.getByRole('button', { name: 'About Append', exact: true })
  const description = page.getByText('Add text to the end.', { exact: true })
  await expect(description).toHaveCount(0)
  const row = info.locator('..')
  const before = await row.boundingBox()
  await info.hover()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await expect(description).toBeVisible()
  const after = await row.boundingBox()
  expect(after!.height).toBe(before!.height)
  const tooltip = await page.getByRole('tooltip').boundingBox()
  expect(tooltip!.x).toBeGreaterThanOrEqual(0)
  expect(tooltip!.x + tooltip!.width).toBeLessThanOrEqual(viewport.width)
  expect(tooltip!.y).toBeGreaterThanOrEqual(0)
  expect(tooltip!.y + tooltip!.height).toBeLessThanOrEqual(viewport.height)
  await page.screenshot({ path: `../docs/catalog-tooltip-${viewport.width}.png` })
  await expect(info).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('heading', { name: 'Transformations', exact: true }).hover()
  await expect(description).toHaveCount(0)
  await info.focus()
  await expect(description).toBeVisible()
  await info.press('Escape')
  await expect(description).toHaveCount(0)
  await info.click()
  await expect(description).toBeVisible()
  await expect(page.locator('.step')).toHaveCount(2)
  await info.click()
  await expect(description).toHaveCount(0)
  await page.getByRole('button', { name: 'Add Append', exact: true }).click()
  await expect(page.locator('.step')).toHaveCount(3)
  await expect(page.getByLabel('Output text')).toHaveText('Real Python!!')
  const lastInfo = page.getByRole('button', { name: 'About URL encode/decode', exact: true })
  await lastInfo.click()
  await expect(page.getByRole('tooltip')).toBeVisible()
  const lastTooltip = await page.getByRole('tooltip').boundingBox()
  expect(lastTooltip!.y + lastTooltip!.height).toBeLessThanOrEqual(viewport.height)
  await page.getByRole('region', { name: 'Available transformations' }).evaluate(el => { el.scrollTop = 0 })
  await expect(lastInfo).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('tooltip').filter({ hasText: 'Encode or decode a URL component' })).toHaveCount(0)
 })
}
